"""
domain/punctuation.py — расстановка запятых по базовым правилам русского языка.

Логика намеренно проста: цель — дать пользователю отправную точку,
а не заменить полноценный синтаксический анализатор.
"""

import re


def local_punctuate(text: str) -> dict:
    """
    Расставляет запятые по базовым правилам.
    Возвращает dict с полями: original, result, explanations, note.
    """
    result = str(text or "").strip()
    explanations: list[str] = []

    def apply(pattern: str, replacement: str, note: str) -> None:
        nonlocal result
        updated = re.sub(pattern, replacement, result, flags=re.IGNORECASE)
        if updated != result:
            result = updated
            if note not in explanations:
                explanations.append(note)

    # ── Подчинительные союзы ─────────────────────────────────────────────────
    apply(r"\s+(потому что)\b",              r", \1", "Запятая перед «потому что».")
    apply(r"\s+(так как)\b",                 r", \1", "Запятая перед «так как».")
    apply(r"\s+(так что)\b",                 r", \1", "Запятая перед «так что».")
    apply(r"\s+(чтобы)\b",                   r", \1", "Запятая перед «чтобы».")
    apply(r"\s+(что)\b",                     r", \1", "Запятая перед «что».")
    apply(r"\s+(если)\b",                    r", \1", "Запятая перед «если».")
    apply(r"\s+(когда)\b",                   r", \1", "Запятая перед «когда».")
    apply(r"\s+(хотя)\b",                    r", \1", "Запятая перед «хотя».")
    apply(r"\s+(словно|будто|как будто)\b",  r", \1", "Запятая перед сравнительным союзом.")

    # ── Сочинительные союзы ──────────────────────────────────────────────────
    apply(r"\s+(но)\s+",                     r", \1 ", "Запятая перед «но».")
    apply(r"\s+(а)\s+",                      r", \1 ", "Запятая перед «а».")
    apply(r"\s+(однако)\s+",                 r", \1 ", "Запятая перед «однако».")

    # ── Начало с придаточного ────────────────────────────────────────────────
    apply(
        r"^(Когда\s+[^,]{3,60}?)(\s+)(?=[А-Яа-яЁё])",
        r"\1, ",
        "Запятая после придаточного с «когда».",
    )
    apply(
        r"^(Если\s+[^,]{3,60}?)(\s+)(?=[А-Яа-яЁё])",
        r"\1, ",
        "Запятая после придаточного с «если».",
    )

    # ── Финальная очистка ────────────────────────────────────────────────────
    result = re.sub(r"\s+,", ",", result)       # пробел перед запятой
    result = re.sub(r",\s*,", ",", result)      # двойные запятые
    result = re.sub(r"\s{2,}", " ", result).strip()

    if result and not re.search(r"[.!?]$", result):
        result += "."

    if not explanations:
        explanations.append("Точного правила не найдено. Проверь вручную.")

    return {
        "original":     text,
        "result":       result,
        "explanations": explanations,
        "note":         "Запятые расставлены по базовым правилам. Обязательно проверьте вручную.",
    }
